"""
Milestone 5 - send the generated email as a TEST to your own inbox via the Gmail API.

Safety design:
  * The recipient is ALWAYS config.TEST_RECIPIENT_EMAIL (your address, from .env).
    There is no parameter to send anywhere else - the prospect's address is only
    printed inside the email body for your reference.
  * Nothing is sent unless `approved=True` is passed, which the Streamlit app only
    does after you tick the approval box and click Send.
  * The subject is prefixed with [TEST].

One-time setup (see README): create an OAuth "Desktop app" client in Google Cloud,
download it as credentials.json into this folder, set TEST_RECIPIENT_EMAIL in .env.
The first send opens a browser window to let you authorise the app (scope: send only).
"""

import base64
import os
from email.message import EmailMessage

import config

SCOPES = ["https://www.googleapis.com/auth/gmail.send"]   # send-only: cannot read your mail


class GmailError(Exception):
    pass


def check_ready():
    """Returns a list of problems that prevent sending (empty list = ready)."""
    problems = []
    r = config.TEST_RECIPIENT_EMAIL
    if not r or "@" not in r:
        problems.append("TEST_RECIPIENT_EMAIL is not set in .env (must be your own address).")
    if not os.path.exists(config.GMAIL_CREDENTIALS_FILE):
        problems.append(f"Gmail OAuth file '{config.GMAIL_CREDENTIALS_FILE}' not found.")
    return problems


def build_test_message(draft, company_url, to=None):
    """Build the MIME email. To: is the test recipient (yours unless a configured extra)."""
    contact = draft.contact
    msg = EmailMessage()
    msg["To"] = to or config.TEST_RECIPIENT_EMAIL
    msg["Subject"] = f"[TEST] {draft.subject}"
    header = (
        "=== TEST EMAIL - generated by the Sprinto outreach assignment app ===\n"
        f"Company: {company_url}\n"
        f"Intended prospect (NOT emailed): {contact.get('full_name')} "
        f"<{contact.get('email')}>, {contact.get('position')}"
        + ("  [MOCK CONTACT]" if contact.get("is_mock") else "") + "\n"
        f"Draft status: {draft.status}; AI mode: {draft.mode}\n"
        "======================================================================\n\n"
    )
    msg.set_content(header + draft.body)
    return msg


def _gmail_service():
    from google.auth.transport.requests import Request
    from google.oauth2.credentials import Credentials
    from google_auth_oauthlib.flow import InstalledAppFlow
    from googleapiclient.discovery import build

    creds = None
    if os.path.exists(config.GMAIL_TOKEN_FILE):
        creds = Credentials.from_authorized_user_file(config.GMAIL_TOKEN_FILE, SCOPES)
    if not creds or not creds.valid:
        if creds and creds.expired and creds.refresh_token:
            creds.refresh(Request())
        else:
            flow = InstalledAppFlow.from_client_secrets_file(config.GMAIL_CREDENTIALS_FILE, SCOPES)
            creds = flow.run_local_server(port=0)   # opens your browser once
        with open(config.GMAIL_TOKEN_FILE, "w") as f:
            f.write(creds.to_json())
    return build("gmail", "v1", credentials=creds)


def send_test_email(draft, company_url, approved=False, service=None):
    """Send `draft` to YOUR inbox only. Returns the Gmail message id."""
    if not approved:
        raise GmailError("Not sent: explicit approval is required.")
    problems = check_ready()
    if problems:
        raise GmailError("Not sent: " + " ".join(problems))
    if not draft.body.strip():
        raise GmailError("Not sent: the draft is empty.")

    msg = build_test_message(draft, company_url)
    if msg["To"] != config.TEST_RECIPIENT_EMAIL:          # belt-and-braces check
        raise GmailError("Not sent: recipient is not the configured test address.")
    raw = base64.urlsafe_b64encode(msg.as_bytes()).decode()
    try:
        service = service or _gmail_service()
        sent = service.users().messages().send(userId="me", body={"raw": raw}).execute()
    except GmailError:
        raise
    except Exception as e:
        raise GmailError(f"Gmail API error: {e}")
    return sent.get("id")
